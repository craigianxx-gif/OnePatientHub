from django.shortcuts import render, redirect
from django.contrib.auth.decorators import login_required
from django.db.models import Q
from django.contrib import messages
from .models import AuditLog

@login_required
def audit_trail_view(request):
    is_global_view = request.user.is_superuser
    
    # 1. Enforce Role-Based Access Control (RBAC)
    try:
        user_role = request.user.profile.role
    except AttributeError:
        user_role = None

    if not is_global_view and user_role not in ['administrator', 'Facility Admin', 'System Admin']:
        messages.error(request, "Access Denied: You do not have the required clearance to view Security Logs.")
        return redirect("dashboard_home")

    # 2. Establish Tenant Isolation Data Pool
    if is_global_view:
        # Ministry of Health View: See everything
        facility_name = "Ministry of Health Global System"
        base_logs = AuditLog.objects.select_related('user').all()
    else:
        # Facility View: Only see logs generated by staff bound to this clinic
        active_facility = request.user.profile.facility
        
        if not active_facility:
            messages.error(request, "Security Alert: Your account is not bound to a registered facility.")
            return redirect("dashboard_home")
            
        facility_name = active_facility.facility_name
        base_logs = AuditLog.objects.filter(
            user__profile__facility=active_facility
        ).select_related('user')

    # Apply default sorting
    logs = base_logs.order_by("-timestamp")

    # 3. Handle Search and Filtering
    query = request.GET.get("q", "").strip().upper()
    module_filter = request.GET.get("module", "").strip()

    if query:
        # Map common terms to standard CRUD actions if needed
        action_mapping = {
            "ADD": "CREATE",
            "NEW": "CREATE",
            "EDIT": "UPDATE",
            "CHANGE": "UPDATE",
            "REMOVE": "DELETE",
            "DEL": "DELETE",
            "VIEW": "VIEW",
        }
        
        # Check if the search query maps to a standard CRUD keyword
        mapped_action = action_mapping.get(query, query)

        logs = logs.filter(
            Q(description__icontains=query) |
            Q(user__username__icontains=query) |
            Q(action__icontains=query) |
            Q(action__icontains=mapped_action) |
            Q(module__icontains=query) |
            Q(object_id__icontains=query)
        )

    if module_filter:
        logs = logs.filter(module=module_filter)

    # Fetch distinct modules for the dropdown filter (only from the tenant's isolated data)
    modules = base_logs.values_list("module", flat=True).distinct()

    return render(
        request,
        "audit/audit_trail.html",
        {
            "logs": logs[:150], # Limit to 150 for performance on the UI
            "query": request.GET.get("q", ""), 
            "selected_module": module_filter,
            "modules": modules,
            "facility_name": facility_name,
            "is_global_view": is_global_view
        }
    )